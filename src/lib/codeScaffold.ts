/*
 * 生成「可直接运行」的代码文件：把模型答案 + 题面样例拼成能本地跑起来的完整程序。
 *
 * 用途有两层：
 * 1. 本地执行器（WASM）跑不动的语言（Java / C / C++ / Go）——给出带样例的完整文件，用户在自己 IDE 里跑；
 * 2. 核心代码模式的题——答案只有函数，补一个读取样例、调用函数、打印结果的驱动。
 *
 * 原则：生成不出来就明说（runnable=false + note），不要造一个看起来能跑其实跑不起来的文件。
 */
import { normalizeOutput, type CodeSample, type RunMode } from './codeQuestion';

export interface ScaffoldInput {
  language: string;
  code: string;
  mode: RunMode;
  samples: CodeSample[];
}

export interface Scaffold {
  filename: string;
  content: string;
  /** 是否生成了可直接运行的完整程序 */
  runnable: boolean;
  note?: string;
}

const EXTENSIONS: Record<string, string> = {
  python: 'py', javascript: 'js', java: 'java', cpp: 'cpp', c: 'c', go: 'go',
};

const LINE_COMMENT: Record<string, string> = {
  python: '#', javascript: '//', java: '//', cpp: '//', c: '//', go: '//',
};

function commentBlock(language: string, lines: string[]): string {
  const mark = LINE_COMMENT[language] ?? '//';
  return lines.map((line) => (line ? `${mark} ${line}` : mark)).join('\n');
}

function sampleBlock(samples: CodeSample[]): string[] {
  const lines: string[] = ['', 'Samples from the question (paste into custom input to run):'];
  samples.forEach((sample, index) => {
    lines.push(`Sample ${index + 1} input:`);
    sample.input.split('\n').forEach((line) => lines.push(`  ${line}`));
    if (sample.output) {
      lines.push(`Sample ${index + 1} expected output:`);
      sample.output.split('\n').forEach((line) => lines.push(`  ${line}`));
    }
  });
  return lines;
}

/** 从核心代码模式的答案里找出入口：类名 + 方法名 + 参数名。 */
function findEntry(code: string): { className: string; method: string; params: string[] } | null {
  const classMatch = /class\s+(\w+)/.exec(code);
  const methodMatch = /(?:public\s+)?(?:static\s+)?(?:def\s+(\w+)\s*\(([^)]*)\)|(?:function\s+)?(\w+)\s*=\s*(?:function\s*)?\(([^)]*)\)|function\s+(\w+)\s*\(([^)]*)\))/.exec(code);
  if (!methodMatch) return null;
  const method = methodMatch[1] || methodMatch[3] || methodMatch[5] || '';
  if (!method || method === '__init__') return null;
  const rawParams = methodMatch[2] || methodMatch[4] || methodMatch[6] || '';
  const params = rawParams
    .split(',')
    .map((param) => param.trim())
    .filter(Boolean)
    .map((param) => param.split(/[:=]/)[0].trim())
    .filter((param) => param && param !== 'self' && param !== 'this');
  return { className: classMatch?.[1] ?? '', method, params };
}


const PYTHON_DRIVER = `
def __mianxu_parse(raw):
    import ast, re
    args = {}
    for part in re.split(r',\\s*(?=[A-Za-z_]\\w*\\s*=)', raw.strip()):
        if '=' not in part:
            continue
        key, value = part.split('=', 1)
        try:
            args[key.strip()] = ast.literal_eval(value.strip())
        except Exception:
            args[key.strip()] = value.strip()
    return args


def __mianxu_main():
    import json, sys
    raw = sys.stdin.read()
    args = __mianxu_parse(raw)
    names = [name for name in __PARAMS__]
    values = [args.get(name) for name in names]
    result = __CALL__(*values)
    if isinstance(result, (list, dict, tuple)):
        print(json.dumps(result, ensure_ascii=False, separators=(',', ':')))
    elif isinstance(result, bool):
        print('true' if result else 'false')
    else:
        print(result)


if __name__ == '__main__':
    __mianxu_main()
`;

const JS_DRIVER = `
function __mianxuParse(raw) {
  const args = {};
  for (const part of raw.split(/,\\s*(?=[A-Za-z_]\\w*\\s*=)/)) {
    const index = part.indexOf('=');
    if (index < 0) continue;
    const key = part.slice(0, index).trim();
    const value = part.slice(index + 1).trim();
    try { args[key] = JSON.parse(value.replace(/'/g, '"')); } catch { args[key] = value; }
  }
  return args;
}

function __mianxuMain() {
  const raw = require('fs').readFileSync(0, 'utf8');
  const args = __mianxuParse(raw);
  const names = __PARAMS__;
  const result = __CALL__(...names.map((name) => args[name]));
  if (Array.isArray(result) || (result && typeof result === 'object')) console.log(JSON.stringify(result));
  else console.log(result);
}

__mianxuMain();
`;

/**
 * 生成可运行脚手架。
 * - ACM 模式：答案本身就是完整程序，原样输出并附样例说明。
 * - 核心代码模式：Python / JavaScript 会补驱动（读样例 → 调用 → 打印）；其余语言只附样例说明。
 */
export function buildScaffold({ language, code, mode, samples }: ScaffoldInput): Scaffold {
  const ext = EXTENSIONS[language] ?? 'txt';
  const filename = `solution.${ext}`;
  const body = code.replace(/\s+$/, '');
  const header = commentBlock(language, ['Generated by Mianxu as a runnable file.', ...sampleBlock(samples)]);

  if (mode === 'acm') {
    return { filename, content: `${header}\n\n${body}\n`, runnable: true };
  }

  // 只有 Python / JavaScript 能自动补驱动；其他语言直接给带样例的文件，让用户自己补 main。
  if (language !== 'python' && language !== 'javascript') {
    return { filename, content: header + '\n\n' + body + '\n', runnable: false, note: 'no-driver-for-language' };
  }

  const entry = findEntry(body);
  if (!entry) {
    return {
      filename,
      content: `${header}\n\n${body}\n`,
      runnable: false,
      note: 'no-callable-signature',
    };
  }

  if (language === 'python') {
    const call = entry.className ? `${entry.className}().${entry.method}` : entry.method;
    const driver = PYTHON_DRIVER
      .replace('__PARAMS__', JSON.stringify(entry.params))
      .replace('__CALL__', call);
    return { filename, content: `${header}\n\n${body}\n${driver}`, runnable: true };
  }

  if (language === 'javascript') {
    const call = entry.className ? `new ${entry.className}().${entry.method}` : entry.method;
    const driver = JS_DRIVER
      .replace('__PARAMS__', JSON.stringify(entry.params))
      .replace('__CALL__', call);
    return { filename, content: `${header}\n\n${body}\n${driver}`, runnable: true };
  }

  return {
    filename,
    content: `${header}\n\n${body}\n`,
    runnable: false,
    note: 'no-driver-for-language',
  };
}

/** 比对单组样例：JSON 结构相等或文本归一化后相等都算通过。 */
export function matchesExpected(actual: string, expected: string): boolean {
  const left = normalizeOutput(actual);
  const right = normalizeOutput(expected);
  if (left === right) return true;
  const looksJson = /^[[{]/.test(right) && /^[[{]/.test(left);
  if (!looksJson) return false;
  try {
    return JSON.stringify(JSON.parse(left)) === JSON.stringify(JSON.parse(right));
  } catch {
    return false;
  }
}
